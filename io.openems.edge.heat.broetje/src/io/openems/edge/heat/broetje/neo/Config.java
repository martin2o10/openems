package io.openems.edge.heat.broetje.neo;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Heat Broetje BLW NEO", //
		description = "Broetje BLW NEO heat pump via NEO-RKM communication module (Modbus TCP or RTU)")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "heatPump0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Read-Only mode", description = "Only read values; never write setpoints to the heat pump")
	boolean readOnly() default true;

	@AttributeDefinition(name = "Min. electric power [W]", description = "Lowest electric power the compressor can modulate to (see datasheet)")
	int minPower() default 800;

	@AttributeDefinition(name = "Max. electric power [W]", description = "Highest electric power of the compressor (see datasheet)")
	int maxPower() default 3500;

	@AttributeDefinition(name = "Min. run time [s]", description = "Minimum compressor run time after a start")
	int minRunTime() default 1200;

	@AttributeDefinition(name = "Min. off time [s]", description = "Minimum compressor off time before a restart")
	int minOffTime() default 600;

	@AttributeDefinition(name = "Write interval [s]", description = "Interval for cyclic writes; the NEO-RKM requires at least 5 s")
	int writeInterval() default 10;

	@AttributeDefinition(name = "Modbus-ID", description = "ID of Modbus bridge.")
	String modbus_id() default "modbus0";

	@AttributeDefinition(name = "Modbus Unit-ID", description = "The Unit-ID of the Modbus device.")
	int modbusUnitId() default 1;

	@AttributeDefinition(name = "Modbus target filter", description = "This is auto-generated by 'Modbus-ID'.")
	String Modbus_target() default "(enabled=true)";

	String webconsole_configurationFactory_nameHint() default "Heat Broetje BLW NEO [{id}]";

}

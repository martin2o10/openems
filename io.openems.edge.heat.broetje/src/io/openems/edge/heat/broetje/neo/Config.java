package io.openems.edge.heat.broetje.neo;

import org.osgi.service.metatype.annotations.AttributeDefinition;
import org.osgi.service.metatype.annotations.ObjectClassDefinition;

@ObjectClassDefinition(//
		name = "Heat Broetje BLW NEO", //
		description = "Broetje BLW NEO heat pump via NEO-RKM communication module (Modbus TCP). "
				+ "Read-only by default; the write path is only active if 'Read-Only mode' is disabled.")
@interface Config {

	@AttributeDefinition(name = "Component-ID", description = "Unique ID of this Component")
	String id() default "heatPump0";

	@AttributeDefinition(name = "Alias", description = "Human-readable name of this Component; defaults to Component-ID")
	String alias() default "";

	@AttributeDefinition(name = "Is enabled?", description = "Is this Component enabled?")
	boolean enabled() default true;

	@AttributeDefinition(name = "Modbus-ID", description = "ID of Modbus bridge.")
	String modbus_id() default "modbus0";

	@AttributeDefinition(name = "Modbus target filter", description = "This is auto-generated by 'Modbus-ID'.")
	String Modbus_target() default "(enabled=true)";

	@AttributeDefinition(name = "Modbus Unit-ID", description = "The Unit-ID of the Modbus device.")
	int modbusUnitId() default 1;

	@AttributeDefinition(name = "Read-Only mode", description = "Only read values; never write setpoints to the heat pump. Default true: no Modbus write access at all.")
	boolean readOnly() default true;

	@AttributeDefinition(name = "Min. electric power [W]", description = "Lowest electric power the compressor can modulate to (see datasheet)")
	int minPower() default 800;

	@AttributeDefinition(name = "Max. electric power [W]", description = "Highest electric power of the compressor (see datasheet)")
	int maxPower() default 3500;

	@AttributeDefinition(name = "Min. run time [s]", description = "Minimum compressor run time after a start")
	int minRunTimeSeconds() default 1200;

	@AttributeDefinition(name = "Min. off time [s]", description = "Minimum compressor off time before a restart")
	int minOffTimeSeconds() default 600;

	@AttributeDefinition(name = "Write interval [s]", description = "Interval for cyclic writes; the NEO-RKM requires at least 5 s (enforced in code)")
	int writeIntervalSeconds() default 10;

	@AttributeDefinition(name = "Read pressures", description = "Poll optional pressure registers 21/22")
	boolean readPressures() default false;

	@AttributeDefinition(name = "Read source temperatures", description = "Poll optional source temperatures 15/16")
	boolean readSourceTemperatures() default false;

	@AttributeDefinition(name = "Read refrigerant temperatures", description = "Poll optional refrigerant temperatures 17-20 (suction gas/evaporation/condensation/hot gas)")
	boolean readRefrigerantTemperatures() default false;

	@AttributeDefinition(name = "Read pump flags", description = "Poll optional pump flags 23/24")
	boolean readPumpFlags() default false;

	@AttributeDefinition(name = "Read volume flow", description = "Poll optional volume flow register 28")
	boolean readFlowRate() default false;

	@AttributeDefinition(name = "Read fresh water temperature", description = "Poll optional fresh water temperature register 31")
	boolean readFreshWaterTemperature() default false;

	@AttributeDefinition(name = "Read delayed outdoor temperature", description = "Poll optional delayed outdoor temperature register 33")
	boolean readDelayedOutdoorTemperature() default false;

	@AttributeDefinition(name = "Read mixer circuit setpoints", description = "Poll optional mixer circuit setpoints 35/36")
	boolean readMixerCircuitSetpoints() default false;

	@AttributeDefinition(name = "Read expansion valve", description = "Poll optional expansion valve register 40")
	boolean readExpansionValve() default false;

	@AttributeDefinition(name = "Read operating hours", description = "Poll optional operating hours registers 42/44")
	boolean readOperatingHours() default false;

	@AttributeDefinition(name = "Read holding registers", description = "Poll optional holding registers 101-106")
	boolean readHoldingRegisters() default false;

	@AttributeDefinition(name = "Read compressor speed setpoint", description = "Poll optional compressor speed setpoint register 126")
	boolean readSpeedSetpoint() default false;

	@AttributeDefinition(name = "Read external request", description = "Poll optional external request registers 117/127")
	boolean readExternalRequest() default false;

	@AttributeDefinition(name = "Read external sensor overrides", description = "Poll optional external sensor override registers 129-134")
	boolean readExternalSensorOverrides() default false;

	@AttributeDefinition(name = "Read second stage", description = "Poll optional second stage registers 147/148")
	boolean readSecondStage() default false;

	String webconsole_configurationFactory_nameHint() default "Heat Broetje BLW NEO [{id}]";

}
